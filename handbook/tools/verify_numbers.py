#!/usr/bin/env python3
"""Exact-arithmetic checks for every worked example in the handbook.

This script uses only the Python standard library. It prints a transcript and
writes it to reports/verification.txt. Integer token arithmetic is exact.
AMM and percentage displays use Decimal with explicit rounding; they are
models, not measurements of a deployed pool.

Usage:
    python -I verify_numbers.py [--output PATH]
"""
from __future__ import annotations

import argparse
import hashlib
from decimal import Decimal, getcontext
from fractions import Fraction
from pathlib import Path

getcontext().prec = 50
ROOT = Path(__file__).resolve().parents[1]
LINES: list[str] = []


def out(text: str = "") -> None:
    print(text)
    LINES.append(text)


def h(title: str) -> None:
    out()
    out(title)
    out("-" * len(title))


def eq(label: str, got, want) -> None:
    if got != want:
        raise AssertionError(f"{label}: got {got!r}, want {want!r}")
    out(f"PASS  {label}: {got!r}")


def addr(decimal: str) -> str:
    n = int(decimal)
    assert 0 <= n < 2**160
    return "0x%040x" % n


def pct(value: Fraction | Decimal) -> str:
    d = Decimal(value.numerator) / Decimal(value.denominator) if isinstance(value, Fraction) else Decimal(value)
    return f"{d * 100:.12f}%"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", default=str(ROOT / "reports" / "verification.txt"))
    args = ap.parse_args(argv[1:])

    out("Honey-POT handbook arithmetic verification")
    out("Generated by tools/verify_numbers.py (standard library only).")
    out("Integer token/wei arithmetic is exact; decimal displays are models.")

    h("1. Decimal address literals used by the hidden control plane")
    A = "178607940065137046348733521910879985571412708986"
    B = "686197854011229533619447624007587113080310915153"
    C = "17860794006513704634733521910879985571412708986"
    D = "570329899025738970963394674811034510039273195112"
    eq("A", addr(A), "0x1f490e99657cd08a058c6bb6cd81dd38f59e0e7a")
    eq("B", addr(B), "0x78322d0c5768c9ca370ddfc1d44db0fef3a6e051")
    eq("C", addr(C), "0x0320e7dc23bfae74334d93c20051125ca59e0e7a")
    eq("D", addr(D), "0x63e67a280645edf97880c1df03c8301b151c4668")
    out("A and C are distinct. C differs from A in the decimal digits that were")
    out("obscured by a fake-keccak comment; it is not a checksum variant of A.")

    h("2. Five-fragment address assembly")
    parts = [0x7ADDAD09, 0xCBD98D97, 0xEC3DA7A0, 0x088EADFE, 0x5801C336]
    assembled = (parts[0] << 128) | (parts[1] << 96) | (parts[2] << 64) | (parts[3] << 32) | parts[4]
    P = "0x" + "%040x" % assembled
    eq("assembled P", P, "0x7addad09cbd98d97ec3da7a0088eadfe5801c336")
    eq("each fragment is 32 bits", [x.bit_length() <= 32 for x in parts], [True] * 5)
    out("P is a hard-coded privilege address, not a DEX pair discovered at runtime.")

    h("3. S6/S7/S9 buy accounting (1 ETH at 18 decimals)")
    one_eth = 10**18
    buy_fee = 5
    fee = one_eth * buy_fee // 100
    after = one_eth - fee
    eq("1 ETH in wei", one_eth, 1_000_000_000_000_000_000)
    eq("5% fee in wei/base units", fee, 50_000_000_000_000_000)
    eq("credited to feeManager", after, 950_000_000_000_000_000)
    eq("credited to token contract", fee, 50_000_000_000_000_000)
    out(f"Total new ledger credit = {after + fee} base units = 1.0 token at 18 decimals.")
    out("totalSupply is not increased in buy(); ETH is retained by the contract.")
    out("Therefore sum(balanceOf) increases without a matching supply increase, and")
    out("there is no path in these three contracts that pays ETH back out to a seller.")

    h("4. 100% fee cap is not a safety cap")
    amount = 1000
    for rate in (5, 10, 100):
        f = amount * rate // 100
        eq(f"fee at {rate}% of {amount}", (f, amount - f), (amount * rate // 100, amount - amount * rate // 100))
    eq("100% sell leaves recipient with", amount - amount * 100 // 100, 0)
    out("The checks are `<= 100`, so the maximum accepted rate is 100%, not 99%.")

    h("5. Fee round trip and break-even multiplier")
    for b, s in ((5, 10), (10, 10), (5, 5), (100, 0)):
        keep = Fraction(100 - b, 100) * Fraction(100 - s, 100)
        out(f"buy {b:3d}% / sell {s:3d}% -> remaining fraction {keep} = {pct(keep)}")
    keep_5_10 = Fraction(95, 100) * Fraction(90, 100)
    eq("5% buy + 10% sell", keep_5_10, Fraction(855, 1000))
    eq("5% buy + 10% sell percent", pct(keep_5_10), "85.500000000000%")
    eq("100% sell fee remaining", Fraction(0, 100), 0)
    out(f"Break-even price multiple after 5%/10% = {Decimal(1) / (Decimal(855) / Decimal(1000)):.12f}x")

    h("6. Double-credit helper: supply unchanged, sum of balances rises")
    supply = 1000
    alice = 100
    amount = 100
    # _transferTo/_balanceView perform two `balances[to] += amount` operations.
    alice_after = alice + 2 * amount
    eq("recipient after helper", alice_after, 300)
    eq("supply after helper", supply, 1000)
    eq("sum of balances delta", alice_after - alice, 200)
    out("Two Transfer(0 -> recipient) events are emitted, but totalSupply is untouched.")
    out("The extra `(_to, _amount);` tuple in viewBalance/transferTo is a no-op; it")
    out("does not add a third credit.")

    h("7. S1-S3 overwrite mint: accounting changes without supply change")
    before = 100
    mint_value = 500
    after_mint = mint_value  # balances[miner] = value, not += value
    eq("balance after overwrite", after_mint, 500)
    eq("delta", after_mint - before, 400)
    eq("totalSupply delta", 0, 0)
    out("An overwrite can reduce a balance (value < before) as easily as increase it.")

    h("8. Dilution from minting")
    S, s, m = 1_000_000, 100_000, 1_000_000
    before_share = Fraction(s, S)
    after_share = Fraction(s, S + m)
    eq("holder share before", pct(before_share), "10.000000000000%")
    eq("holder share after mint", pct(after_share), "5.000000000000%")
    out("Assumes the minted amount is not distributed to the holder and supply rises by m.")

    h("9. S14 initialize double-counts totalSupply")
    T = 1_000_000 * 10**18
    # initialize sets totalSupply = T, then _mint(msg.sender, T) adds T again.
    eq("totalSupply after initialize", T + T, 2_000_000 * 10**18)
    eq("balance after initialize", T, 1_000_000 * 10**18)
    out("This is an internal invariant break in the initialization path, independent")
    out("of the public-initialize front-running risk.")

    h("10. AMM constant-product fee model and pool drain")
    gamma = Fraction(997, 1000)
    out("Model: selling m tokens into a pool with token reserve x and quote reserve y")
    out("returns dy = gamma*m*y/(x + gamma*m). If y is large, the fraction of the")
    out("quote reserve removed is gamma*m/(x + gamma*m).")
    x = 1_000_000
    for m in (1_000_000, 10_000_000, 1_000_000_000, 1_000_000_000_000):
        frac = gamma * m / (x + gamma * m)
        out(f"x={x:,}, m={m:,} -> gamma*m/(x+gamma*m) = {pct(frac)}")
    f1 = gamma * 1_000_000 / (x + gamma * 1_000_000)
    eq("m=x drain fraction", f"{pct(f1)}", "49.924887330996%")
    out("This is a model with integer-rounding ignored. It does not predict a real")
    out("pool without reserves, decimals, and router behavior.")

    h("11. Hash and duplicate-file claim")
    canonical = [
        "contracts/honeypot/session-01-honeypot-v1.sol",
        "contracts/honeypot/session-02-honeypot-v1-2.sol",
        "contracts/honeypot/session-03-honeypot-v1-solidity-0.8.19.sol",
        "contracts/honeypot/session-04-whitelist-antibot-honeypot.sol",
        "contracts/honeypot/session-05-blacklist-detector-proof-honeypot.sol",
        "contracts/honeypot/session-06-switchable-honeypot-mode.sol",
        "contracts/honeypot/session-07-whitelist-switchable-honeypot.sol",
        "contracts/honeypot/session-08-v2-blacklist-detector-proof.sol",
        "contracts/honeypot/session-09-v2-whitelist-switchable.sol",
        "contracts/token/session-10-normal-meme-token.sol",
        "contracts/token/session-11-ownership-renounce-meme-token.sol",
        "contracts/token/session-12-auto-ownership-renounce-meme-token.sol",
        "contracts/token/session-13-unlimited-supply-meme-token.sol",
        "contracts/token/session-14-v2-unlimited-supply-meme-token.sol",
        "contracts/token/session-15-v2-auto-ownership-renounce-meme-token.sol",
    ]
    for rel in canonical:
        p = ROOT.parent / rel
        # Handbook copies are checked by check_manifest.py; this script reports
        # the canonical parent repository when present.
        if p.exists():
            digest = hashlib.sha256(p.read_bytes()).hexdigest()
            out(f"{digest[:16]}…  {rel}")

    h("12. Scope limitations")
    out("No Solidity compiler was available during this review; these are static")
    out("calculations over source, not compiled bytecode. No chain fork, mempool, or")
    out("router execution was performed. Decimal displays are rounded for readability;")
    out("the assertions above use exact integers or Fractions.")

    outpath = Path(args.output)
    outpath.parent.mkdir(parents=True, exist_ok=True)
    outpath.write_text("\n".join(LINES) + "\n", encoding="utf-8")
    out(f"\nWrote {outpath}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(__import__("sys").argv))
